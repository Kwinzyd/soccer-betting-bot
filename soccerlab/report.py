"""Render an evaluation JSON as a Markdown report. Pure formatting."""


def _ci(c, pct=False, digits=4):
    if not c or c.get("lo") is None:
        return "n/a"
    m = c.get("mean", c.get("value"))
    if pct:
        return f"{100 * m:+.2f}% [{100 * c['lo']:+.2f}%, {100 * c['hi']:+.2f}%]"
    return f"{m:+.{digits}f} [{c['lo']:+.{digits}f}, {c['hi']:+.{digits}f}]"


def render(r):
    L = []
    a = L.append
    pop = r["population"]
    a(f"# {r['experiment']} — point-in-time evaluation report")
    a("")
    a("Generated by `python -m soccerlab backtest` from frozen inputs (fingerprints at the end). "
      "Pre-registration: [docs/EXPERIMENT_PLAN.md](../docs/EXPERIMENT_PLAN.md). "
      "All seasons here were previously viewed during legacy development: this is a "
      "**retrospective** evaluation, not an independent holdout.")
    a("")
    a("## Verdict")
    a("")
    g = r["gates"]
    a("| gate | status |")
    a("|---|---|")
    for k in "ABCDEFG":
        a(f"| {k} | {g[k]['status']} |")
    a("")
    a(f"**{g['promotion']}**")
    a("")
    a("## Population")
    a("")
    a(f"Primary window {pop['seasons']}: **{pop['primary_common']}** fixtures with a Pinnacle closing price "
      f"and predictions from every compared model ({pop['primary_with_early_market']} also have the "
      f"Pinnacle pre-closing price). All final fixtures 2023-2026: {pop['all_final_rows']}.")
    a("")
    a("## Forecast quality (primary window, identical fixtures)")
    a("")
    a("| model | n | log-loss | Brier | ECE |")
    a("|---|---|---|---|---|")
    for k, v in sorted(r["primary"]["forecast"].items(), key=lambda kv: kv[1]["logloss"]):
        a(f"| `{k}` | {v['n']} | {v['logloss']:.4f} | {v['brier']:.4f} | {v['ece']:.4f} |")
    a("")
    a("Paired log-loss difference vs the market (negative = model better), 95% bootstrap CI:")
    a("")
    a("| comparison | n | Δ, fixture-clustered | Δ, week-clustered |")
    a("|---|---|---|---|")
    for k, v in r["primary"]["paired"].items():
        a(f"| {k} | {v['n']} | {_ci(v['fixture'])} | {_ci(v['week'])} |")
    a("")
    a("### Robustness: Δ (pit_v1 close − market close) by league and season")
    a("")
    a("| slice | n | Δ [95% CI] |")
    a("|---|---|---|")
    for k, v in r["by_league_delta"].items():
        a(f"| {k} | {v['n']} | {_ci(v)} |")
    for k, v in r["by_season_delta"].items():
        a(f"| season {k} | {v['n']} | {_ci(v)} |")
    a("")
    a("Season log-loss vs naive base rates (all final fixtures, incl. those without odds):")
    a("")
    a("| season | n | pit_v1 | base rates | ECE |")
    a("|---|---|---|---|---|")
    for s, v in r["by_season_ece"].items():
        a(f"| {s} | {v['n']} | {v['logloss']:.4f} | {v['logloss_base_rates']:.4f} | {v['ece']:.4f} |")
    a("")
    a("### Lead time (fixtures with both early and closing Pinnacle prices)")
    a("")
    a("| model | n | log-loss |")
    a("|---|---|---|")
    for k, v in r["early_population"].items():
        a(f"| `{k}` | {v['n']} | {v['logloss']:.4f} |")
    a("")
    a("### Blend test (incremental information)")
    a("")
    for k, b in r["blend"].items():
        a(f"* `{k}`: weight on model chosen on {b['fit_seasons']} = **{b['w_star']:.2f}**; applied to "
          f"{b['test_seasons']}: Δ vs market alone {_ci(b['test_delta'])}")
    a("")
    a("### Calibration, pit_v1 close (primary window)")
    a("")
    a("| outcome | band | n | mean pred | freq | gap |")
    a("|---|---|---|---|---|---|")
    for lab, tbl in r["calibration_pit_v1_close"].items():
        for b in tbl:
            a(f"| {lab} | {b['lo']:.2f}-{b['hi']:.2f} | {b['n']} | {b['mean_pred']:.3f} | {b['freq']:.3f} | {b['gap']:+.3f} |")
    a("")
    a("## Leakage attribution")
    a("")
    a("`legacy` is the unmodified legacy model (with its look-ahead). `pit_xg_r14` has the same "
      "structure (xG blend 0.3, ~14-day refits) under point-in-time rules. The difference is the part of "
      "the legacy result attributable to look-ahead plus minor implementation differences.")
    a("")
    for k, v in r["leakage"].items():
        a(f"* {k}: Δ log-loss {_ci(v['fixture'])} (n={v['n']})")
    a("")
    a("Point-in-time promoted-team priors (atk, def, cohorts, teams) per league-season:")
    a("")
    for k, v in r["pit_promoted_priors"].items():
        if v:
            a(f"* {k}: atk {v[0]:+.3f}, def {v[1]:+.3f} from {v[2]} cohort(s), {v[3]} team-seasons")
    a("")
    a("## Betting policies (flat 1u, one selection per fixture, decimal prices)")
    a("")
    a("| policy | bets | ROI [95% CI, fixture] | ROI [week blocks] | profit u | max DD u | ROI w/o top-10 |")
    a("|---|---|---|---|---|---|---|")
    for k, v in r["policies"].items():
        if not v.get("n"):
            a(f"| {k} | 0 | — | — | — | — | — |")
            continue
        wo = v.get("roi_without_top10_winners")
        a(f"| {k} | {v['n']} | {_ci(v['roi'], pct=True)} | {_ci(v['roi_week_blocks'], pct=True)} | "
          f"{v['profit_units']:+.1f} | {v['max_drawdown_units']:.1f} | "
          f"{'n/a' if wo is None else f'{100 * wo:+.2f}%'} |")
    a("")
    a("Selection-specific CLV vs the documented Pinnacle closing price (early policies):")
    a("")
    a("| policy | n | odds ratio entry/close − 1 | EV at close fair | fair-prob move | % beating close |")
    a("|---|---|---|---|---|---|")
    for k, v in r["policies"].items():
        c = v.get("clv")
        if c and c.get("n"):
            a(f"| {k} | {c['n']} | {_ci(c['odds_ratio'], pct=True)} | {_ci(c['ev_vs_close_fair'], pct=True)} | "
              f"{_ci(c['prob_move'], pct=True)} | {100 * c['pct_beat_close']:.1f}% |")
    a("")
    a("Notes: Pinnacle 'early' = football-data PSH/PSD/PSA, collected Friday/Tuesday, not a true opening "
      "price. `EARLY-MAX` and `SHOP-*` use the market-maximum column, which is not guaranteed executable "
      "(different books, limits, timing); treat as an upper bound. Flat stakes, so stake-weighted and "
      "unweighted CLV coincide.")
    a("")
    if "legacy_readme_reproduction" in r:
        rr = r["legacy_readme_reproduction"]
        a("## Legacy README reproduction")
        a("")
        a(f"{rr['note']}. Here ({rr['seasons_available_here']}): legacy n={rr['legacy']['n']} "
          f"log-loss {rr['legacy']['logloss']:.4f}, market {rr['mkt_close']['logloss']:.4f}.")
        a("")
    a("## Input fingerprints")
    a("")
    a("```")
    for k, v in r["fingerprints"].items():
        if isinstance(v, dict):
            for f, h in sorted(v.items()):
                a(f"{h}  balldontlie_consolidated/{f}")
        else:
            a(f"{v}  model/{k}")
    a("```")
    a("")
    a(f"Runtime {r.get('runtime_seconds')}s.")
    return "\n".join(L) + "\n"
